// Lists every production dependency of the mobile app (transitively) with its license.
// Output: docs/legal/third-party-licenses.md. Run: node scripts/build-licenses.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
const root = process.cwd();
const seen = new Map();
function pkgDir(name, from) {
  let dir = from;
  for (;;) {
    const p = join(dir, 'node_modules', name);
    if (existsSync(join(p, 'package.json'))) return p;
    const up = dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}
function walk(name, from) {
  const dir = pkgDir(name, from);
  if (!dir || seen.has(name)) return;
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const lic = typeof pj.license === 'string' ? pj.license : pj.license?.type ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN');
  seen.set(name, { version: pj.version, license: lic, repo: typeof pj.repository === 'string' ? pj.repository : pj.repository?.url ?? '' });
  for (const dep of Object.keys(pj.dependencies ?? {})) walk(dep, dir);
}
const app = JSON.parse(readFileSync('apps/mobile/package.json', 'utf8'));
for (const d of Object.keys(app.dependencies)) if (!d.startsWith('@adultingos/')) walk(d, join(root, 'apps/mobile'));
const rows = [...seen.entries()].sort(([a], [b]) => a.localeCompare(b));
const byLic = {};
for (const [, v] of rows) byLic[v.license] = (byLic[v.license] ?? 0) + 1;
writeFileSync('docs/legal/third-party-licenses.md',
  `# Third-party licenses (mobile app)\n\nGenerated by \`scripts/build-licenses.mjs\` from installed packages: ${rows.length} production packages.\n\n` +
  `Summary: ${Object.entries(byLic).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(', ')}.\n\n` +
  `Bundled fonts: Inter and Plus Jakarta Sans — SIL Open Font License 1.1. Icons: Feather (MIT) via @expo/vector-icons.\n\n` +
  `| Package | Version | License |\n|---|---|---|\n` + rows.map(([n, v]) => `| ${n} | ${v.version} | ${v.license} |`).join('\n') + '\n');
console.log(rows.length, 'packages;', JSON.stringify(byLic));
