/**
 * Generates supabase/seeds/01_reference_data.sql from the shared TypeScript
 * sources of truth (mascots, achievements, feature flags, guide drafts), so the
 * app bundle and the database never disagree. Run: npx tsx scripts/build-seed.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ACHIEVEMENTS, GUIDE_PACK } from '../packages/shared/src/index';
import { MASCOTS, MASCOT_IDS } from '../packages/brand/src/index';
import { FEATURE_FLAGS } from '../apps/mobile/src/config/featureFlags';

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(',')}]::text[]`;
const lines: string[] = [
  '-- GENERATED by scripts/build-seed.ts — do not edit by hand.',
  'begin;',
  "select set_config('adultingos.publishing', 'on', true);",
];

for (const id of MASCOT_IDS) {
  const m = MASCOTS[id];
  lines.push(`insert into public.mascots (id, name, role, phrase) values (${q(id)}, ${q(m.name)}, ${q(m.role)}, ${q(m.phrase)}) on conflict (id) do update set name = excluded.name, role = excluded.role, phrase = excluded.phrase;`);
}
for (const a of ACHIEVEMENTS) {
  lines.push(`insert into public.achievements (key, title, description, mascot_id, xp, released) values (${q(a.key)}, ${q(a.title)}, ${q(a.description)}, ${q(a.mascot)}, ${a.xp}, ${a.released}) on conflict (key) do update set title = excluded.title, description = excluded.description, xp = excluded.xp, released = excluded.released;`);
}
for (const [key, f] of Object.entries(FEATURE_FLAGS)) {
  lines.push(`insert into public.feature_flags (key, enabled, description) values (${q(key)}, ${f.production}, ${q(f.description)}) on conflict (key) do nothing;`);
}

for (const g of GUIDE_PACK) {
  const gid = `(select id from public.guides where slug = ${q(g.slug)})`;
  lines.push(
    `insert into public.guides (slug, title, category, agency, jurisdiction, audience, summary, eligibility_caveats, helpful_notes, fees_text, processing_time_text, related_slugs, status, content_version, last_verified_on, published_at) values (${q(g.slug)}, ${q(g.title)}, ${q(g.category)}, ${q(g.agency)}, ${q(g.jurisdiction)}, ${q(g.audience)}, ${q(g.summary)}, ${q(g.eligibilityCaveats)}, ${q(g.helpfulNotes)}, ${q(g.feesText)}, ${q(g.processingTimeText)}, ${arr(g.related)}, ${q(g.status)}, ${g.status === 'published' ? 1 : 0}, ${q(g.lastVerifiedOn)}, ${g.status === 'published' ? 'now()' : 'null'}) on conflict (slug) do nothing;`,
  );
  g.requirements.forEach((r, i) => lines.push(`insert into public.guide_requirements (guide_id, position, text) values (${gid}, ${i + 1}, ${q(r)}) on conflict do nothing;`));
  g.steps.forEach((s, i) =>
    lines.push(`insert into public.guide_steps (guide_id, position, title, body, is_optional, suggested_offset_days) values (${gid}, ${i + 1}, ${q(s.title)}, ${q(s.body)}, ${!!s.optional}, ${s.offsetDays ?? 0}) on conflict do nothing;`),
  );
  for (const s of g.sources) {
    lines.push(`insert into public.guide_sources (guide_id, title, url, publisher, is_official, verified_on) select ${gid}, ${q(s.title)}, ${q(s.url)}, ${q(s.publisher)}, ${s.isOfficial}, ${q(s.verifiedOn)} where not exists (select 1 from public.guide_sources where guide_id = ${gid} and url = ${q(s.url)});`);
  }
  if (g.status === 'published') {
    // Users read published snapshots (published_guides()); build version 1 exactly like publish_guide().
    lines.push(
      `insert into public.guide_versions (guide_id, version, snapshot) select g.id, 1, jsonb_build_object(` +
        `'guide', to_jsonb(g) - 'status', ` +
        `'requirements', coalesce((select jsonb_agg(to_jsonb(r) order by r.position) from public.guide_requirements r where r.guide_id = g.id), '[]'), ` +
        `'steps', coalesce((select jsonb_agg(to_jsonb(s) order by s.position) from public.guide_steps s where s.guide_id = g.id), '[]'), ` +
        `'sources', coalesce((select jsonb_agg(to_jsonb(s)) from public.guide_sources s where s.guide_id = g.id), '[]')) ` +
        `from public.guides g where g.slug = ${q(g.slug)} on conflict (guide_id, version) do nothing;`,
    );
    const chunks: [string, string][] = [
      [`${g.title} — overview`, [g.summary, `Who it is for: ${g.audience}`, `Caveats: ${g.eligibilityCaveats}`, g.helpfulNotes].filter(Boolean).join('\n')],
      ...(g.requirements.length ? [[`${g.title} — what you need`, g.requirements.map((r) => `- ${r}`).join('\n')] as [string, string]] : []),
      ...g.steps.map((s, i) => [`${g.title} — step ${i + 1}: ${s.title}`, s.body] as [string, string]),
    ];
    chunks.forEach(([h, c], i) =>
      lines.push(`insert into public.knowledge_chunks (guide_id, guide_version, chunk_index, heading, content) values (${gid}, 1, ${i}, ${q(h)}, ${q(c)}) on conflict do nothing;`),
    );
  }
}
lines.push("select set_config('adultingos.publishing', 'off', true);", 'commit;', '');
writeFileSync(join(__dirname, '../supabase/seeds/01_reference_data.sql'), lines.join('\n'));
console.log(`Seed written: ${lines.length} statements`);
